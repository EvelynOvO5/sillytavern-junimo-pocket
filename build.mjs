import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('./', import.meta.url);
const html = await readFile(new URL('source.html', base), 'utf8');
let script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
script = script.replace(/let uiRoot=document,uiDocument=document;[\s\S]*?const actions=/, 'let uiDocument=document;\nconst actions=');
script = script.replace('baseFunds=12580,', 'upgradeBaseFunds=12580,');
script = 'let baseFunds=12580;\n' + script;
script = script.split('\n').filter(line => !line.startsWith('window.JunimoMap=') && !line.startsWith('try{const stRoot=')).join('\n');
const css = html.match(/<style[^>]*>([\s\S]*?)<\/style>/)[1];
const body = html.match(/<body[^>]*>([\s\S]*?)<script>/)[1];
const progression_ui=await readFile(new URL('progression-ui.js',base),'utf8');
const animal_ui=await readFile(new URL('animal-ui.js',base),'utf8');
const transfer_ui=await readFile(new URL('transfer-ui.js',base),'utf8');
const collectionUI=await readFile(new URL('collection-ui.js',base),'utf8');
const communityBundle=(await readFile(new URL('community-ui.js',base),'utf8'))+'\nextra.textContent+='+JSON.stringify((await readFile(new URL('community-base.css',base),'utf8'))+(await readFile(new URL('social-design.css',base),'utf8')))+';';
const transferUI=await readFile(new URL('transfer-ui.js',base),'utf8');
const groupSocialUI=await readFile(new URL('group-social-ui.js',base),'utf8');
const customizationUI=await readFile(new URL('customization-ui.js',base),'utf8');
const taskBatchUI=await readFile(new URL('task-batch-ui.js',base),'utf8');
const adapter = (await readFile(new URL('adapter.js', base), 'utf8')).replace('/* PROGRESSION_UI */',()=>progression_ui).replace('/* ANIMAL_UI */',()=>animal_ui).replace('/* TRANSFER_UI */',()=>transferUI).replace('/* COLLECTION_UI */',()=>collectionUI).replace('/* COMMUNITY_UI */',()=>communityBundle).replace('/* GROUP_SOCIAL_UI */',()=>groupSocialUI).replace('/* CUSTOMIZATION_UI */',()=>customizationUI).replace('/* TASK_BATCH_UI */',()=>taskBatchUI);
await writeFile(new URL('phone.js', base), `// Generated by build.mjs from the supplied design and adapter.js.\nexport function mountPhone(uiRoot, bridge) {\nuiRoot.innerHTML = ${JSON.stringify('<style>'+css+'</style>'+body)};\n${script}\n${adapter}\n}\n`);
console.log('Built phone.js');

